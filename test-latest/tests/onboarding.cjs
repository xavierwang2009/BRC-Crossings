const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/../src/app.js', 'utf8');
const next = source.slice(source.indexOf('  next() {'), source.indexOf('  prev() {'));
const ctx = vm.createContext({ S: { step:5, companionChosen:true, petName:'Pebble', mainFocus:'parenting', screen:'onboard', stack:[{screen:'home'}], joined:[] }, world:null, render(){}, toast(){}, t:key=>key, suggestedCircles:()=>['c1'] });
vm.runInContext('const actions = {' + next + '}; actions.next();',ctx);
assert.equal(ctx.S.screen,'circles','Enter the community should open Circles, not the public Home');
assert.equal(ctx.S.stack.length,0);
assert.equal(ctx.S.draftFocus,'parenting');
assert.deepEqual(Array.from(ctx.S.joined),['c1'],'A new Member joins the Circle suggested for their main Focus Area, not a fixed one');
ctx.S.screen='onboard'; ctx.S.petName='';
vm.runInContext('actions.next()',ctx);
assert.equal(ctx.S.screen,'onboard');
const prev = source.slice(source.indexOf('  prev() {'), source.indexOf('  getStarted() {'));
const back = vm.createContext({ S: { step:1, screen:'onboard', stack:[{screen:'home'}] }, render(){} });
vm.runInContext('function back() { const p = S.stack.pop() || { screen: "home" }; Object.assign(S, p); } const actions = {' + prev + '}; actions.prev();', back);
assert.equal(back.S.screen,'home','Back from step 1 should return to Home when setup started there');
back.S.screen='onboard'; back.S.step=1; back.S.stack=[];
vm.runInContext('actions.prev()', back);
assert.equal(back.S.screen,'onboard'); assert.equal(back.S.step,0,'With no earlier screen, step 1 steps back to step 0');
back.S.step=3; back.S.stack=[{screen:'home'}];
vm.runInContext('actions.prev()', back);
assert.equal(back.S.step,2);
const reset = source.slice(source.indexOf('  erase() {'), source.indexOf('  cwTab('));
const store = new Map([['key', JSON.stringify({member:true, history:['old'], friendMessages:{kevin:['private']}})]]);
const resetCtx = vm.createContext({ S:{lang:'ht'}, PERSIST:true, SAVE_KEY:'key', localStorage:{setItem:(k,v)=>store.set(k,v)}, t:k=>k, confirm:()=>false, crypto:{randomUUID:()=>'next'}, location:{reload(){}} });
vm.runInContext('const actions = {' + reset + '}; actions.erase();', resetCtx);
assert.equal(JSON.parse(store.get('key')).member,true,'Cancel keeps the current profile');
resetCtx.confirm=()=>true;
vm.runInContext('actions.erase()',resetCtx);
assert.deepEqual(JSON.parse(store.get('key')), {lang:'ht',generation:'next'}, 'A fresh tester keeps only the language and reset marker');
console.log('Onboarding, companion validation, Back and confirmed tester reset passed.');
