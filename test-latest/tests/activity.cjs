const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/../src/app.js', 'utf8');
const helpers = source.split('/* ---------- activity dates and streaks ---------- */')[1].split('/* ---------- activity presentation ---------- */')[0];
const ctx = vm.createContext({ S: { history: [] }, Date });
vm.runInContext(helpers, ctx);
const stats = (dates, today) => JSON.parse(JSON.stringify(ctx.streakStats(dates.map(date => ({date})), today)));
assert.deepEqual(stats([], '2026-11-02'), {current:0,longest:0});
assert.deepEqual(stats(['2026-10-31','2026-11-01'], '2026-11-02'), {current:2,longest:2});
assert.deepEqual(stats(['2026-10-29','2026-10-30','2026-10-31'], '2026-11-02'), {current:0,longest:3});
assert.deepEqual(stats(['2026-10-31','2026-11-01','2026-11-02','2026-11-02'], '2026-11-02'), {current:3,longest:3});
assert.deepEqual(stats(['2026-11-03'], '2026-11-02'), {current:0,longest:0});
assert.equal(ctx.shiftDay('2024-03-01',-1), '2024-02-29');
assert.equal(ctx.shiftDay('2027-01-01',-1), '2026-12-31');
assert.equal(ctx.recordMood('good','2026-11-02'),true);
assert.equal(ctx.recordMood('sad','2026-11-02'),false);
assert.equal(ctx.S.history.length,1);
assert.equal(ctx.S.history[0].mood,'sad');
assert.equal(ctx.recordMood('okay','2026-11-03'),true);
console.log('Activity checks passed: streak gaps, duplicates, future dates, DST-date boundary, leap year, year boundary, same-day update.');
