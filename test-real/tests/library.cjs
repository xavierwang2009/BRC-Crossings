const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const content = fs.readFileSync(__dirname + '/../src/content.js', 'utf8');
const app = fs.readFileSync(__dirname + '/../src/app.js', 'utf8');
const S = { practiceQuery: '', practiceKind: '', practiceTopic: '', practiceDuration: '', practiceLanguage: '', savedOnly: false, savedPractices: [] };
const ctx = vm.createContext({ S });
vm.runInContext(content + app.split('/* ---------- practice filtering ---------- */')[1].split('/* ---------- practice presentation ---------- */')[0], ctx);
const ids = () => Array.from(ctx.filteredPractices(), r => r.id);
assert.equal(ids().length, 12);
S.practiceQuery = '  WORKDAY  ';
assert.deepEqual(ids(), ['work']);
Object.assign(S, { practiceQuery: '', practiceTopic: 'career', practiceDuration: 'medium', practiceLanguage: 'ht' });
assert.deepEqual(ids(), ['work']);
S.practiceQuery = '工作';
assert.deepEqual(ids(), ['work']);
S.practiceDuration = 'short';
assert.deepEqual(ids(), ['stretch-desk']);
Object.assign(S, { practiceQuery: '', practiceTopic: '', practiceDuration: 'long', practiceLanguage: '' });
assert.deepEqual(ids(), ['listen', 'future', 'family-doodle', 'walk-notice']);
Object.assign(S, { practiceDuration: '', savedOnly: true, savedPractices: ['notice'] });
assert.deepEqual(ids(), ['notice']);
S.savedPractices = [];
assert.deepEqual(ids(), []);
Object.assign(S, { savedOnly: false, practiceKind: 'music' });
assert.deepEqual(ids(), ['mood-playlist', 'hum-breathe']);
Object.assign(S, { practiceKind: 'movement', practiceDuration: 'short' });
assert.deepEqual(ids(), ['stretch-desk']);
console.log('Library checks passed: combined filters, kinds of support, duration boundaries, multilingual search, empty results, saved-only.');
