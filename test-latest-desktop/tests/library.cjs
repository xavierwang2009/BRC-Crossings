const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const content = fs.readFileSync(__dirname + '/../src/content.js', 'utf8');
const app = fs.readFileSync(__dirname + '/../src/app.js', 'utf8');
const S = { practiceQuery: '', practiceTopic: '', practiceDuration: '', practiceLanguage: '', savedOnly: false, savedPractices: [] };
const ctx = vm.createContext({ S });
vm.runInContext(content + app.split('/* ---------- practice filtering ---------- */')[1].split('/* ---------- practice presentation ---------- */')[0], ctx);
const ids = () => Array.from(ctx.filteredPractices(), r => r.id);
assert.equal(ids().length, 6);
S.practiceQuery = '  WORKDAY  ';
assert.deepEqual(ids(), ['work']);
Object.assign(S, { practiceQuery: '', practiceTopic: 'career', practiceDuration: 'medium', practiceLanguage: 'ht' });
assert.deepEqual(ids(), ['work']);
S.practiceQuery = '工作';
assert.deepEqual(ids(), ['work']);
S.practiceDuration = 'short';
assert.deepEqual(ids(), []);
Object.assign(S, { practiceQuery: '', practiceTopic: '', practiceDuration: 'long', practiceLanguage: '' });
assert.deepEqual(ids(), ['listen', 'future']);
Object.assign(S, { practiceDuration: '', savedOnly: true, savedPractices: ['notice'] });
assert.deepEqual(ids(), ['notice']);
S.savedPractices = [];
assert.deepEqual(ids(), []);
console.log('Library checks passed: combined filters, duration boundaries, multilingual search, empty results, saved-only.');
